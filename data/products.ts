// Helper functions for catalog queries
export function getAllProducts(): Product[] {
  return products;
}

export function getProductsByCategory(category: string): Product[] {
  if (category === "all") return products;
  if (category === "crochet-single") {
    return products.filter((p) => p.category === "crochet-flowers" && p.crochetSubcategory === "single");
  }
  if (category === "crochet-bouquets") {
    return products.filter((p) => p.category === "crochet-flowers" && p.crochetSubcategory === "bouquet");
  }
  if (category === "bouquet-1") {
    return products.filter((p) => p.category === "crochet-flowers" && p.bouquetType === "1-flower");
  }
  if (category === "bouquet-3") {
    return products.filter((p) => p.category === "crochet-flowers" && p.bouquetType === "3-flower");
  }
  return products.filter((p) => p.category === category);
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}
